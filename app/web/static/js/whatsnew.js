const latest = () => CHANGES[0].version;

/** Есть ли версия, которую ещё не открывали. */
export function hasNews() {
  return getPref('whatsNew') !== latest();
}

export function whatsNewRow() {
  return `<button class="drawer-link whats-new" id="drawerWhatsNew">Что нового в ${esc(latest())}
    ${hasNews() ? '<span class="news-dot" aria-label="новое"></span>' : ''}</button>`;
}

export function openWhatsNew() {
  tap();
  const body = pushScreen('Что нового');
  body.innerHTML = CHANGES.map(({ version, items }) => `<div class="card whats-new-card">
      <div class="card-title">Версия ${esc(version)}</div>
      ${items.map(([icon, title, text]) => `<div class="wn-item"><span class="wn-ico">${icon}</span>
        <span><b>${esc(title)}</b><span class="muted small wn-text">${esc(text)}</span></span></div>`).join('')}
    </div>`).join('');
  if (hasNews()) setPref('whatsNew', latest());
  document.querySelector('#drawerWhatsNew .news-dot')?.remove();
}
