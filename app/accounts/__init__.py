"""Вход без Telegram: аккаунт с почтой и паролем.

Пользователь дневника по-прежнему одна строка в users с ключом telegram_id.
У тех, кто пришёл без Telegram, это служебный номер из отдельного диапазона
(WEB_ID_BASE и выше): настоящие id Telegram до него не доходят, а бот по
таким номерам ничего в Telegram не отправляет. Привязка Telegram позже
переносит все данные на настоящий id.
"""

# Настоящие id Telegram — до ~10^10. Служебные — с 8·10^15: меньше 2^53,
# поэтому и в JavaScript остаются точными целыми.
WEB_ID_BASE = 8_000_000_000_000_000


def has_telegram(telegram_id: int) -> bool:
    """Есть ли у пользователя настоящий Telegram (а не служебный номер)."""
    return 0 < telegram_id < WEB_ID_BASE
